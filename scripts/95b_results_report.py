#!/usr/bin/env python3
"""
Every result this work reports, in one file, generated from the data.

WHY
---
The manuscript is prose, and prose is where a number goes stale. This stage
writes the numbers the manuscript is made of into a single plain-text report:
what was assessed, under which reading, with which rule, and what each stage
found. Nothing here is typed by hand -- every figure is read from
derived/processed/*.csv or from the eval/ report that owns it -- so the file
can be regenerated after any change and diffed against the last one.

It is not a substitute for scripts/99_audit.py, which checks the manuscript
against the same data. This is the other direction: the data, assembled so that
prose can be written or rewritten from it.

Inputs  : derived/processed/*.csv, eval/*.md
Outputs : eval/RESULTS.md

Usage:  python scripts/95b_results_report.py
"""

from __future__ import annotations

import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "derived" / "processed"
EVAL = ROOT / "eval"

IND = ("possible_exceedance", "precondition_unmet", "method_insufficient",
       "indeterminate_unresolved", "indeterminate_other")


def rows(name):
    p = PROC / name
    if not p.exists():
        return []
    with p.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def section(md_name, heading, first=None, last=None):
    """A section of an eval report, quoted verbatim.

    Verbatim because the report that owns a number is the one that computed it;
    re-deriving it here would create a second implementation of the same count,
    which is the defect this project keeps finding in itself.
    """
    p = EVAL / md_name
    if not p.exists():
        return [f"_({md_name} not generated)_", ""]
    text = p.read_text(encoding="utf-8").splitlines()
    out, on = [], first is None
    for line in text:
        if first and line.startswith(first):
            on = True
        elif on and last and line.startswith(last):
            break
        if on:
            out.append(line)
    return out or [f"_(section not found in {md_name})_", ""]


def pct(a, b):
    return f"{100 * a / b:.1f} %" if b else "—"


def main() -> int:
    L = []
    A = L.append

    A("# Results, assembled from the data")
    A("")
    A("Generated by `scripts/95b_results_report.py`. Every number is read from "
      "`derived/processed/*.csv` or quoted from the `eval/` report that "
      "computed it; nothing is typed here. Regenerate after any change and "
      "diff this file to see what moved.")
    A("")

    # ---------------------------------------------------------------- source
    A("## 1  What was assessed")
    A("")
    summ = {r["scope"] + "|" + r.get("key", ""): r for r in rows("waterbase_summary.csv")}
    tot = next((r for r in rows("waterbase_summary.csv")
                if r["scope"] == "total"), None)
    au = {r["quantity"]: r["value"] for r in rows("assessment_unit.csv")}
    if tot:
        A(f"- river station-years in the aggregated release: **{int(tot['n']):,}**")
        A(f"- samples represented: **{int(tot['samples']):,}**")
    if au:
        A(f"- station-years a European annual-average standard reaches: "
          f"**{int(au['assessed_rows']):,}**")
        A(f"- distinct station–substance–year keys: "
          f"**{int(au['assessed_distinct_station_substance_year']):,}** "
          f"({au['share_pct']} % of rows are a second row for a key already "
          f"seen)")
    A("")

    # ------------------------------------------------------------- headline
    A("## 2  The three-valued assessment")
    A("")
    read = defaultdict(dict)
    for r in rows("verdict_readings.csv"):
        read[r["reading"]][r["censo_outcome"]] = int(r["n"])
    if read:
        A("Three readings of the same rows. **headline** is the procedure the "
          "paper uses; **row_level** treats every conditional standard as unmet, "
          "which is what a reader of one row alone can do; "
          "**censored_guard_band** applies the uncertainty band to a censored "
          "limit as well, the precautionary reading the paper reports and does "
          "not use.")
        A("")
        outs = ["compliant", "exceedance", "possible_exceedance",
                "method_insufficient", "precondition_unmet",
                "indeterminate_unresolved", "indeterminate_other"]
        A("| outcome | " + " | ".join(read) + " |")
        A("|---|" + "---|" * len(read))
        for o in outs:
            if any(read[k].get(o) for k in read):
                A(f"| `{o}` | " + " | ".join(f"{read[k].get(o, 0):,}"
                                             for k in read) + " |")
        A("| **undecidable** | " + " | ".join(
            pct(sum(read[k].get(o, 0) for o in IND), sum(read[k].values()))
            for k in read) + " |")
        A("")

    A("### How each standard's applicability was decided")
    A("")
    rt = defaultdict(lambda: defaultdict(int))
    for r in rows("applicability_routes.csv"):
        rt[r["route"]][r["censo_outcome"]] = int(r["n"])
    if rt:
        A("| route | assessments | undecidable |")
        A("|---|---|---|")
        for route, d in sorted(rt.items(), key=lambda kv: -sum(kv[1].values())):
            t = sum(d.values())
            A(f"| {route} | {t:,} | "
              f"{pct(sum(d.get(o, 0) for o in IND), t)} |")
        A("")

    fl = rows("assessment_flags.csv")
    if fl:
        A("### Flags, which never change a verdict")
        A("")
        A("| flag | n |")
        A("|---|---|")
        for r in fl:
            A(f"| {r['flag']} | {int(r['n']):,} |")
        A("")

    # --------------------------------------------------------- counterfactual
    A("## 3  What a two-valued pipeline reports for the same rows")
    A("")
    cell = defaultdict(int)
    for r in rows("waterbase_verdicts_population.csv"):
        cell[(r["substitution"], r["censo_outcome"], r["two_valued_outcome"])] \
            = int(r["n"])
    if cell:
        subs = ("zero", "half", "full")
        exc = {s: sum(v for (a, _, t), v in cell.items()
                      if a == s and t == "exceeding") for s in subs}
        A("| non-detection enters at | exceedances reported |")
        A("|---|---|")
        for s in subs:
            A(f"| {s} | {exc[s]:,} |")
        A(f"| **affirmable in law** | "
          f"**{cell[('zero', 'exceedance', 'exceeding')]:,}** |")
        A("")
        A("Decomposition of the half-limit column, which is the substitution "
          "Article 5(1) of Directive 2009/90/EC requires:")
        A("")
        A("| CENSO outcome of a row the pipeline calls exceeding | n |")
        A("|---|---|")
        for o in ("method_insufficient", "precondition_unmet", "exceedance",
                  "indeterminate_unresolved", "possible_exceedance",
                  "compliant", "indeterminate_other"):
            if cell[("half", o, "exceeding")]:
                A(f"| `{o}` | {cell[('half', o, 'exceeding')]:,} |")
        A("")

    # ------------------------------------------------------------ sensitivity
    A("## 4  Sensitivities")
    A("")
    A("### The uncertainty reading")
    L += section("waterbase_external.md", "", "| reading | band |",
                 "Neither band contains")
    A("")
    A("### The band applied to censored results as well")
    L += section("uncertainty_sensitivity.md", "", "| | n | share |",
                 "## Why the band is not applied")
    A("")
    A("### The join, and the rules that go beyond the guidance")
    L += section("revision_sensitivity.md", "", "| step | kind |",
                 "**Cadmium and its compounds**")
    A("")
    A("### Composition of the record")
    L += section("revision_sensitivity.md", "", "| reading | undecidable |",
                 "| country | assessed rows |")
    A("")

    # -------------------------------------------------------------- by time
    A("## 5  Over time")
    A("")
    yr = rows("exceedances_by_year.csv")
    plotted = [r for r in yr if r.get("plotted") == "yes"]
    if plotted:
        A("| year | assessable | affirmable | undecidable |")
        A("|---|---|---|---|")
        for r in plotted:
            A(f"| {r['year']} | {int(r['assessable']):,} | "
              f"{int(r['affirmable']):,} | {r['undecidable_pct']} % |")
        A("")

    # ------------------------------------------------------- other stages
    A("## 6  The other legal test: the maximum allowable concentration")
    A("")
    L += section("mac_exceedance.md", "", "| verdict | n | share |",
                 "> Excluded:")
    A("")
    L += section("mac_exceedance.md", "", "| annual average | maximum allowable |",
                 "Coverage:")
    A("")

    A("## 7  The same observations under two regulations")
    A("")
    L += section("dual_regulation.md", "", "| Outcome |", "## Where they disagree")
    A("")
    L += section("dual_regulation.md", "", "| EU | TR | n (co-regulated) |",
                 "The two rows worth reading twice")
    A("")

    A("## 8  The vocabulary, and what it was compared against")
    A("")
    L += section("gap_table.md", "", "| Ontology | entities |",
                 "**The `LOD bound to` column")
    A("")
    L += section("exchange_standards.md", "", "| standard | form |",
                 "## Evidence")
    A("")

    A("## 9  The fourth detection status, from a record that supplies it")
    A("")
    L += section("wqp_estimated.md", "", "| status | metals |",
                 "Not written, and why")
    A("")

    A("## 10  Verification")
    A("")
    for name, first, last in (
            ("axiom_tests.md", "- cases", "##"),
            ("owl_profile.md", "- axioms", "##"),
            ("shacl_validation.md", "- graph:", "**What the shapes"),
            # The rule layer against the pipeline. It belongs beside the SHACL
            # run: both say what the shipped artefact does when someone loads
            # it rather than what the analysis did in Python, and a reader
            # weighing the shapes wants the second answer as much as the first.
            ("rule_agreement.md", "- observations sampled", "##"),
            ("competency_questions.md", "- questions", "##"),
            ("decision_flowchart.md", "- tests drawn", "##"),
            ("oops_assessment.md", "| pitfall", "**Reused external"),
            ("foops_assessment.md", "- retrieved", "## By FAIR"),
            ("pipeline_performance.md", "| stage |", "## What is on the"),
            ("audit.md", "- checks", "##")):
        out = section(name, "", first, last)
        if out and not out[0].startswith("_("):
            A(f"**{name}**")
            A("")
            L += out
            A("")

    (EVAL / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    n_tab = sum(1 for x in L if x.startswith("|"))
    print(f"  wrote eval/RESULTS.md ({len(L)} lines, {n_tab} table rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
